#!/usr/bin/env bash
# Compiles the addon's GPU kernels (src/ofxLibRealSense2Kernels.h) to PTX for its CUDA
# processing and embeds the PTX in src/ofxLibRealSense2KernelsPtx.h - the Linux twin of
# build_gpu_kernels.ps1 (same output; the PTX serves Windows and Linux). Only needed after
# editing the kernels. OpenCL compiles the kernel source itself at run time.
#
# Usage: ./build_gpu_kernels.sh [path/to/nvcc]    (default: nvcc on PATH, else /usr/local/cuda)

set -euo pipefail
ADDON="$(cd "$(dirname "$0")/.." && pwd)"
NVCC="${1:-$(command -v nvcc || echo /usr/local/cuda/bin/nvcc)}"
ARCH="${ARCH:-compute_52}"
[ -x "$NVCC" ] || { echo "nvcc not found (pass its path)"; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
# The kernel file is C++ raw string literals around the source: drop the delimiter lines.
grep -Ev '^[[:space:]]*(R"OFXRS2\(|\)OFXRS2")[[:space:]]*$' "$ADDON/src/ofxLibRealSense2Kernels.h" > "$WORK/kernels.cu"
# -fmad=false: no fused multiply-adds, so the kernels round like the CPU code they replace.
"$NVCC" -ptx -arch="$ARCH" -fmad=false -o "$WORK/kernels.ptx" "$WORK/kernels.cu"

VERSION="$("$NVCC" --version | sed -n 's/.*release \([0-9.]*\).*/\1/p')"
OUT="$ADDON/src/ofxLibRealSense2KernelsPtx.h"
{
    echo "// Generated by scripts/build_gpu_kernels from ofxLibRealSense2Kernels.h - do not edit."
    echo "// PTX ($ARCH, -fmad=false), CUDA $VERSION; NUL-terminated."
    echo "#pragma once"
    echo "static const unsigned char ofxLibRealSense2KernelsPtx[] = {"
    { cat "$WORK/kernels.ptx"; printf '\0'; } | od -An -v -tx1 | tr -s ' \n' ' ' | sed 's/^ //; s/ $//' |
        tr ' ' '\n' | sed 's/^/0x/' | paste -sd, - | fold -w 120 | sed 's/^/    /; s/,$//; s/$/,/' | sed 's/^    ,/    /'
    echo "};"
} > "$OUT"
echo "Wrote $OUT (CUDA $VERSION, $ARCH)"
