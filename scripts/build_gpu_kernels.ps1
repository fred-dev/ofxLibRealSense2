# Compiles the addon's GPU kernels (src/ofxLibRealSense2Kernels.h) to PTX for its CUDA
# processing and embeds the PTX in src/ofxLibRealSense2KernelsPtx.h. Only needed after editing
# the kernels: the generated header is committed, and the same PTX serves Windows and Linux.
# (OpenCL compiles the kernel source itself at run time.)
#
# PTX for compute_52 runs on every NVIDIA GPU from Maxwell (GTX 9xx) on: the driver compiles it
# for the GPU it finds (once; it caches the result). Apps then need no CUDA Toolkit and ship no
# CUDA DLLs - only an NVIDIA driver recent enough for the Toolkit that made the PTX (CUDA 12.1:
# driver 530 or newer).
#
# -fmad=false: no fused multiply-adds, so the kernels round like the CPU code they replace.
#
# Requirements: the CUDA Toolkit and Visual Studio's C++ compiler (nvcc preprocesses with it).
#
# Usage (PowerShell):
#   .\build_gpu_kernels.ps1
#   .\build_gpu_kernels.ps1 -CudaPath "C:\Program Files\NVIDIA GPU Computing Toolkit\CUDA\v12.1"

param(
    [string]$CudaPath = $env:CUDA_PATH,
    [string]$Arch = "compute_52"
)

$ErrorActionPreference = "Stop"
$Addon = (Resolve-Path "$PSScriptRoot\..").Path
$nvcc = "$CudaPath\bin\nvcc.exe"
if (-not (Test-Path $nvcc)) { throw "nvcc not found (set -CudaPath or CUDA_PATH)" }

$installer = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer"
$env:PATH = "$installer;$env:PATH"
$vs = & "$installer\vswhere.exe" -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw "Visual Studio with the C++ workload not found" }

$work = Join-Path ([IO.Path]::GetTempPath()) "ofxrs_kernels"
New-Item -ItemType Directory -Force $work | Out-Null
$cu = "$work\ofxLibRealSense2Kernels.cu"
$ptx = "$work\ofxLibRealSense2Kernels.ptx"
# The kernel file is C++ raw string literals around the source: drop the delimiter lines.
Get-Content "$Addon\src\ofxLibRealSense2Kernels.h" | Where-Object { $_ -notmatch '^\s*(R"OFXRS2\(|\)OFXRS2")\s*$' } |
    Set-Content $cu -Encoding ascii

# nvcc needs a host compiler it accepts: the default toolset first, then older ones (CUDA 12.1
# crashes on VS 2026's headers; VS 2022's 14.44 works).
$toolsets = @("") + (Get-ChildItem "$vs\VC\Tools\MSVC" -Directory | Sort-Object { [version]$_.Name } -Descending |
    ForEach-Object { ($_.Name -split '\.')[0..1] -join '.' } | Select-Object -Skip 1 -Unique)
$ok = $false
foreach ($ver in $toolsets) {
    $vcv = if ($ver) { " -vcvars_ver=$ver" } else { "" }
    $cmd = "`$env:PATH = '$installer;' + `$env:PATH; Import-Module '$vs\Common7\Tools\Microsoft.VisualStudio.DevShell.dll'; " +
        "Enter-VsDevShell -VsInstallPath '$vs' -SkipAutomaticLocation -DevCmdArguments '-arch=x64 -host_arch=x64$vcv' | Out-Null; " +
        "& '$nvcc' -allow-unsupported-compiler -D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH -ptx -arch=$Arch -fmad=false -o '$ptx' '$cu'; exit `$LASTEXITCODE"
    Remove-Item $ptx -ErrorAction SilentlyContinue
    $log = powershell -NoProfile -Command $cmd 2>&1
    if ($LASTEXITCODE -eq 0 -and (Test-Path $ptx)) { $ok = $true; Write-Host "nvcc host toolset: $(if ($ver) { $ver } else { 'default' })"; break }
}
if (-not $ok) { $log | Write-Host; throw "nvcc failed with every installed MSVC toolset (last output above)" }

# Embedded as bytes (MSVC limits string literals to 64 KB), NUL-terminated for cuModuleLoadData.
$bytes = [IO.File]::ReadAllBytes($ptx) + [byte]0
$version = (& $nvcc --version | Select-String "release") -replace '.*release ([0-9.]+).*', '$1'
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// Generated by scripts/build_gpu_kernels from ofxLibRealSense2Kernels.h - do not edit.")
[void]$sb.AppendLine("// PTX ($Arch, -fmad=false), CUDA $version; NUL-terminated.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("static const unsigned char ofxLibRealSense2KernelsPtx[] = {")
for ($i = 0; $i -lt $bytes.Length; $i += 24) {
    $line = ($bytes[$i..([Math]::Min($i + 23, $bytes.Length - 1))] | ForEach-Object { "0x{0:x2}" -f $_ }) -join ","
    [void]$sb.AppendLine("    $line,")
}
[void]$sb.AppendLine("};")
$out = "$Addon\src\ofxLibRealSense2KernelsPtx.h"
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"))
Remove-Item -Recurse -Force $work
Write-Host "Wrote $out ($([math]::Round($bytes.Length / 1KB)) KB of PTX, CUDA $version, $Arch)"
